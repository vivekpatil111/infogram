"""Create a VAPID key pair for Web Push.

    python manage.py generate_vapid_keys            # prints env lines
    python manage.py generate_vapid_keys --write    # appends them to backend/.env

The private key is a secret: keep it in the environment (Render: Environment).
"""

import base64

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError


def b64url(raw):
    return base64.urlsafe_b64encode(raw).decode().rstrip("=")


class Command(BaseCommand):
    help = "Generate VAPID keys for Web Push."

    def add_arguments(self, parser):
        parser.add_argument("--write", action="store_true", help="Append to backend/.env instead of printing.")

    def handle(self, *args, write=False, **options):
        key = ec.generate_private_key(ec.SECP256R1())
        private = b64url(key.private_numbers().private_value.to_bytes(32, "big"))
        public = b64url(key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint))
        lines = f"VAPID_PUBLIC_KEY={public}\nVAPID_PRIVATE_KEY={private}\n"
        if not write:
            self.stdout.write(lines)
            return
        env = settings.BASE_DIR / ".env"
        if env.exists() and "VAPID_PRIVATE_KEY=" in env.read_text():
            raise CommandError("backend/.env already has VAPID keys; remove them first to rotate.")
        with env.open("a") as handle:
            handle.write("\n# Web Push (generated by manage.py generate_vapid_keys)\n" + lines)
        self.stdout.write(self.style.SUCCESS("Added VAPID_PUBLIC_KEY and VAPID_PRIVATE_KEY to backend/.env"))
